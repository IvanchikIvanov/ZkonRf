"""Скрипт для загрузки кодексов (пример)."""
from pathlib import Path
from bot.utils.config import settings
from bot.utils.logger import log


def create_sample_codex():
    """Создание примера кодекса для тестирования."""
    codexes_dir = Path(settings.database_path_resolved.parent / "codexes")
    codexes_dir.mkdir(parents=True, exist_ok=True)
    
    sample_codex = """Статья 1. Основные начала гражданского законодательства

1. Гражданское законодательство основывается на признании равенства участников регулируемых им отношений, неприкосновенности собственности, свободы договора, недопустимости произвольного вмешательства кого-либо в частные дела, необходимости беспрепятственного осуществления гражданских прав, обеспечения восстановления нарушенных прав, их судебной защиты.

2. Граждане (физические лица) и юридические лица приобретают и осуществляют свои гражданские права своей волей и в своем интересе. Они свободны в установлении своих прав и обязанностей на основе договора и в определении любых не противоречащих законодательству условий договора.

Статья 2. Отношения, регулируемые гражданским законодательством

1. Гражданское законодательство определяет правовое положение участников гражданского оборота, основания возникновения и порядок осуществления права собственности и других вещных прав, прав на результаты интеллектуальной деятельности и приравненные к ним средства индивидуализации (интеллектуальных прав), регулирует договорные и иные обязательства, а также другие имущественные и личные неимущественные отношения, основанные на равенстве, автономии воли и имущественной самостоятельности участников.

2. Участниками регулируемых гражданским законодательством отношений являются граждане и юридические лица. В регулируемых гражданским законодательством отношениях могут участвовать также Российская Федерация, субъекты Российской Федерации и муниципальные образования.

Статья 3. Гражданское законодательство и иные акты, содержащие нормы гражданского права

1. В соответствии с Конституцией Российской Федерации гражданское законодательство находится в ведении Российской Федерации.

2. Гражданское законодательство состоит из настоящего Кодекса и принятых в соответствии с ним иных федеральных законов, регулирующих отношения, указанные в пунктах 1 и 2 статьи 2 настоящего Кодекса."""
    
    sample_file = codexes_dir / "Гражданский_кодекс_РФ.txt"
    with open(sample_file, "w", encoding="utf-8") as f:
        f.write(sample_codex)
    
    log.info(f"Создан пример кодекса: {sample_file}")


if __name__ == "__main__":
    create_sample_codex()
    log.info("Для загрузки кодексов поместите файлы (.txt или .md) в папку data/codexes/")
    log.info("Затем запустите: python -m scripts.process_codexes")

